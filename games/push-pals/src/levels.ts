import { type Level, parseLevel } from './game/level';

// Difficulty is bounded per chapter and checked by the solver in levels.test.ts. Levels
// are meant to be real puzzles for a young child: no warm-ups, and every level can get
// stuck. Every board is at most 8x8 including walls, so tiles stay big on a phone.

export interface Chapter {
  readonly boxes: number;
  readonly minPushes: number;
  readonly maxPushes: number;
  /** If true, every level in the chapter needs a trick to solve. */
  readonly trick: boolean;
  readonly levels: readonly string[];
}

